// ============================================================
// main.js — точка входа, «дирижёр»
// ============================================================
// Этот файл запускается первым (он подключён последним в index.html).
// Его задачи:
//   1. При загрузке страницы — загрузить список учеников и данные первого.
//   2. При клике на ученика — перезагрузить данные и перерисовать экран.
//   3. Связывать api.js (получение данных) и render.js (отрисовка).
// ============================================================


// ------------------------------------------------------------
// КОНСТАНТЫ
// ------------------------------------------------------------
// Пока на странице один класс — захардкодим его id.
// Позже, когда появится выбор класса, можно сделать динамически.
// ------------------------------------------------------------
const CLASS_ID = 2;


// ------------------------------------------------------------
// loadAndShowStudent(userId)
// ------------------------------------------------------------
// Загружает данные ученика и перерисовывает основную область (справа).
// Также перерисовывает сайдбар, чтобы подсветить активного ученика.
//
// Аргумент:
//   userId — id выбранного ученика
// ------------------------------------------------------------
async function loadAndShowStudent(userId) {
  try {
    // 1. Получаем данные ученика с бэкенда (пока — из мока)
    const data = await loadStudentData(userId, CLASS_ID);

    // 2. Рисуем основную область: имя, прогресс-бары, таблица
    renderStudentData(data);

    // 3. Перерисовываем сайдбар, чтобы подсветить активного ученика.
    //    Список уже загружен — берём из кэша (см. ниже).
    renderStudentList(cachedStudents, userId, loadAndShowStudent);

  } catch (error) {
    // Если что-то пошло не так (например, сервер упал) —
    // выводим ошибку в консоль. Позже можно показать пользователю
    // красивое сообщение в интерфейсе.
    console.error("Ошибка загрузки данных ученика:", error);
  }
}


// ------------------------------------------------------------
// cachedStudents — «кэш» списка учеников
// ------------------------------------------------------------
// Список учеников загружается один раз при старте.
// Дальше мы его переиспользуем, чтобы не дёргать бэкенд на каждый клик.
// Эта переменная объявлена через `let`, потому что её значение
// задаётся позже — уже внутри init().
// ------------------------------------------------------------
let cachedStudents = [];


// ------------------------------------------------------------
// init()
// ------------------------------------------------------------
// Что происходит при загрузке страницы:
//   1. Загружаем список учеников класса.
//   2. Рисуем сайдбар.
//   3. Загружаем данные первого ученика (по умолчанию — первого из списка).
// ------------------------------------------------------------
async function init() {
  try {
    // 1. Загружаем список учеников
    cachedStudents = await loadStudents(CLASS_ID);

    // Если список пуст — дальше идти некуда
    if (cachedStudents.length === 0) {
      console.warn("Список учеников пуст");
      return;
    }

    // 2. Рисуем сайдбар. Активным сразу делаем первого ученика.
    //    Третий аргумент — колбэк: что делать при клике на ученика.
    const firstUserId = cachedStudents[0].user_id;
    renderStudentList(cachedStudents, firstUserId, loadAndShowStudent);

    // 3. Загружаем и отображаем данные первого ученика
    await loadAndShowStudent(firstUserId);

  } catch (error) {
    console.error("Ошибка инициализации:", error);
  }
}


// ------------------------------------------------------------
// СТАРТ
// ------------------------------------------------------------
// Скрипт подключён в конце <body>, поэтому DOM уже построен.
// Можно сразу вызывать init() — не нужно ждать DOMContentLoaded.
// ------------------------------------------------------------
init();